// Brings the scene files in line with storyboard.json: a starter file for each new scene, a preview
// entry per scene (src/entries/<id>.ts, so one broken scene never stops the others from rendering)
// and the registry the film uses. Existing scene files are never touched.
//   node scripts/scaffold.mjs
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const boards = ["storyboard.json", "storyboard-demo.json"]
  .filter((f) => fs.existsSync(path.join(ROOT, f)))
  .map((f) => JSON.parse(fs.readFileSync(path.join(ROOT, f), "utf8")))
const board = { scenes: [...new Map(boards.flatMap((b) => b.scenes).map((s) => [s.id, s])).values()] } // every scene of every cut
const ids = board.scenes.map((s) => s.id)
const scenes = path.join(ROOT, "src", "scenes")
const entries = path.join(ROOT, "src", "entries")
fs.mkdirSync(scenes, { recursive: true })
fs.mkdirSync(entries, { recursive: true })

const starter = (s) => `import { AbsoluteFill } from "remotion"

import type { SceneProps } from "../data"
import { Eyebrow, Title } from "../kit"

// ${s.title}
export default function Scene({ scene }: SceneProps) {
  return (
    <AbsoluteFill style={{ alignItems: "center", justifyContent: "center", gap: 24 }}>
      <Eyebrow>{scene.id}</Eyebrow>
      <Title>{scene.title}</Title>
    </AbsoluteFill>
  )
}
`

for (const s of board.scenes) {
  const file = path.join(scenes, `${s.id}.tsx`)
  if (!fs.existsSync(file)) fs.writeFileSync(file, starter(s))
  fs.writeFileSync(
    path.join(entries, `${s.id}.ts`),
    `// Generated by scripts/scaffold.mjs: this scene alone, for previews and stills.
import { registerRoot } from "remotion"

import { previewRoot } from "../preview"
import View from "../scenes/${s.id}"

registerRoot(previewRoot("${s.id}", View))
`,
  )
}
for (const f of fs.readdirSync(entries)) {
  if (f.endsWith(".ts") && !ids.includes(f.slice(0, -3))) fs.rmSync(path.join(entries, f))
}
const name = (id, i) => `S${i}_${id.replace(/[^a-zA-Z0-9]/g, "_")}`
fs.writeFileSync(
  path.join(scenes, "registry.ts"),
  `// Generated by scripts/scaffold.mjs from storyboard.json.
import type { SceneComponent } from "../stage"
${ids.map((id, i) => `import ${name(id, i)} from "./${id}"`).join("\n")}

export const VIEWS: Record<string, SceneComponent> = {
${ids.map((id, i) => `  "${id}": ${name(id, i)},`).join("\n")}
}
`,
)
console.log(`${ids.length} scenes: ${ids.join(", ")}`)
